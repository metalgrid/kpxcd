// TestGenerateTestKeyForAllTypes verifies that GenerateTestKey works
// for rsa, ed25519, and ecdsa-p256 key types.
func TestGenerateTestKeyForAllTypes(t *testing.T) {
	keyTypes := []string{"rsa", "ed25519", "ecdsa-p256"}

	for _, kt := range keyTypes {
		t.Run(kt, func(t *testing.T) {
			key, err := GenerateTestKey(kt)
			if err != nil {
				t.Fatalf("GenerateTestKey(%q) failed: %v", kt, err)
			}
			if key == nil {
				t.Fatal("GenerateTestKey returned nil")
			}
			if key.Signer == nil {
				t.Error("Signer is nil")
			}
			if len(key.Blob) == 0 {
				t.Error("Blob is empty")
			}
			if key.Format == "" {
				t.Error("Format is empty")
			}
			// Verify the comment follows the expected pattern.
			expectedComment := "test@" + kt
			if key.Comment != expectedComment {
				t.Errorf("Comment = %q, want %q", key.Comment, expectedComment)
			}
		})
	}
}

