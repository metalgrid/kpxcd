// TestIdentityManagerAddReplacesExisting verifies that adding a key
// with the same fingerprint replaces the existing entry.
func TestIdentityManagerAddReplacesExisting(t *testing.T) {
	cfg := &config.SSHAgentConfig{}
	im := NewIdentityManager(cfg)

	key, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}

	_ = im.AddIdentity(key, 0, false, false, "db-old", "entry-old")
	_ = im.AddIdentity(key, 300, true, true, "db-new", "entry-new")

	// Count should still be 1 (replaced, not duplicated).
	if im.Count() != 1 {
		t.Errorf("expected 1 key after replacement, got %d", im.Count())
	}

	found := im.FindIdentityByFingerprint(key.Fingerprint())
	if found == nil {
		t.Fatal("key not found after replacement")
	}
	if found.Lifetime != 300 {
		t.Errorf("Lifetime = %d, want 300", found.Lifetime)
	}
	if !found.Confirm {
		t.Error("Confirm should be true after replacement")
	}
	if found.DBUUID != "db-new" {
		t.Errorf("DBUUID = %q, want db-new", found.DBUUID)
	}
}

// TestIdentityManagerRemoveIdentitiesForDatabase verifies that keys
// belonging to a database can be removed.
func TestIdentityManagerRemoveIdentitiesForDatabase(t *testing.T) {
	cfg := &config.SSHAgentConfig{RemoveOnLock: true}
	im := NewIdentityManager(cfg)

	key1, _ := GenerateTestKey("ed25519")
	key2, _ := GenerateTestKey("rsa")

	// Add key1 with autoRemove=true for db1.
	_ = im.AddIdentity(key1, 0, false, true, "db1", "e1")
	// Add key2 with autoRemove=false for db1.
	_ = im.AddIdentity(key2, 0, false, false, "db1", "e2")

	if im.Count() != 2 {
		t.Fatalf("expected 2 keys, got %d", im.Count())
	}

	im.RemoveIdentitiesForDatabase("db1")

	// key1 should be removed (autoRemove=true), key2 should remain.
	if im.Count() != 1 {
		t.Errorf("expected 1 key after removal, got %d", im.Count())
	}

	found := im.FindIdentityByFingerprint(key2.Fingerprint())
	if found == nil {
		t.Error("key2 (autoRemove=false) should still exist")
	}
}

// TestLoadedKeyFields verifies that LoadedKey stores all fields correctly.
func TestLoadedKeyFields(t *testing.T) {
	cfg := &config.SSHAgentConfig{}
	im := NewIdentityManager(cfg)

	key, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}

	err = im.AddIdentity(key, 120, true, true, "test-db", "test-entry")
	if err != nil {
		t.Fatalf("AddIdentity failed: %v", err)
	}

	found := im.FindIdentityByFingerprint(key.Fingerprint())
	if found == nil {
		t.Fatal("key not found")
	}

	if found.Lifetime != 120 {
		t.Errorf("Lifetime = %d, want 120", found.Lifetime)
	}
	if !found.Confirm {
		t.Error("Confirm should be true")
	}
	if !found.AutoRemove {
		t.Error("AutoRemove should be true")
	}
	if found.DBUUID != "test-db" {
		t.Errorf("DBUUID = %q, want test-db", found.DBUUID)
	}
	if found.EntryUUID != "test-entry" {
		t.Errorf("EntryUUID = %q, want test-entry", found.EntryUUID)
	}
	if !bytes.Equal(found.Key.Blob, key.Blob) {
		t.Error("Key blob mismatch")
	}
}

