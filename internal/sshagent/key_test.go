// TestKeyFingerprint verifies that Key.Fingerprint returns a SHA256
// fingerprint in the correct format.
func TestKeyFingerprint(t *testing.T) {
	key, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}

	fp := key.Fingerprint()

	// Should start with "SHA256:".
	if len(fp) < 7 || fp[:7] != "SHA256:" {
		t.Errorf("fingerprint = %q, should start with SHA256:", fp)
	}

	// Should be consistent across multiple calls.
	fp2 := key.Fingerprint()
	if fp != fp2 {
		t.Errorf("fingerprint not consistent: %q vs %q", fp, fp2)
	}

	// Two different keys should have different fingerprints.
	key2, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}
	fp3 := key2.Fingerprint()
	if fp == fp3 {
		t.Error("different keys should have different fingerprints")
	}
}

// TestKeyFingerprintEmpty verifies that Fingerprint handles empty blob.
func TestKeyFingerprintEmpty(t *testing.T) {
	key := &Key{Blob: nil}
	fp := key.Fingerprint()
	if fp != "SHA256:(empty)" {
		t.Errorf("fingerprint for empty blob = %q, want SHA256:(empty)", fp)
	}

	key2 := &Key{Blob: []byte{}}
	fp2 := key2.Fingerprint()
	if fp2 != "SHA256:(empty)" {
		t.Errorf("fingerprint for empty byte slice = %q, want SHA256:(empty)", fp2)
	}
}

// TestKeyEqual verifies that Key.Equal correctly compares keys by fingerprint.
func TestKeyEqual(t *testing.T) {
	key, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}

	// A key should equal itself.
	if !key.Equal(key) {
		t.Error("key should equal itself")
	}

	// Create a copy with same blob — should be equal.
	key2 := &Key{
		Blob:  make([]byte, len(key.Blob)),
		Comment: key.Comment,
	}
	copy(key2.Blob, key.Blob)
	if !key.Equal(key2) {
		t.Error("keys with same blob should be equal")
	}

	// Different key — should not be equal.
	key3, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}
	if key.Equal(key3) {
		t.Error("different keys should not be equal")
	}

	// nil == nil should be true.
	var nilKey *Key
	if !nilKey.Equal(nilKey) {
		t.Error("nil should equal nil")
	}

	// nil vs non-nil should be false.
	if key.Equal(nil) {
		t.Error("non-nil key should not equal nil")
	}
	if nilKey.Equal(key) {
		t.Error("nil key should not equal non-nil key")
	}
}

// TestParsePrivateKeyEd25519 verifies that ParsePrivateKey can parse
// an Ed25519 key generated by crypto/ed25519, marshaled to OpenSSH format.
func TestParsePrivateKeyEd25519(t *testing.T) {
	key, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}

	// Verify the parsed key has correct properties.
	if key.Format != "ssh-ed25519" {
		t.Errorf("Format = %q, want ssh-ed25519", key.Format)
	}
	if key.Signer == nil {
		t.Fatal("Signer is nil after GenerateTestKey")
	}

	// Verify the public key is valid.
	sshPub := key.Signer.PublicKey()
	if sshPub == nil {
		t.Fatal("PublicKey from signer is nil")
	}
	if sshPub.Type() != "ssh-ed25519" {
		t.Errorf("public key type = %q, want ssh-ed25519", sshPub.Type())
	}

	// Verify we can sign data with the parsed key.
	data := []byte("test signing data")
	sig, err := key.Sign(data)
	if err != nil {
		t.Fatalf("Sign failed: %v", err)
	}
	if sig == nil || len(sig.Blob) == 0 {
		t.Error("signature is empty")
	}

	// Verify the signature can be validated with the public key.
	if err := sshPub.Verify(data, sig); err != nil {
		t.Fatalf("signature verification failed: %v", err)
	}
}

