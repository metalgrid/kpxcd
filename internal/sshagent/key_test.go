// TestIdentityManagerAddRemoveListFindByFingerprint verifies the
// IdentityManager Add, Remove, List, and FindByFingerprint operations.
func TestIdentityManagerAddRemoveListFindByFingerprint(t *testing.T) {
	cfg := &config.SSHAgentConfig{}
	im := NewIdentityManager(cfg)

	if im == nil {
		t.Fatal("NewIdentityManager returned nil")
	}

	// Count should start at 0.
	if im.Count() != 0 {
		t.Errorf("expected 0 keys, got %d", im.Count())
	}

	// Generate and add a key.
	key1, err := GenerateTestKey("ed25519")
	if err != nil {
		t.Fatalf("GenerateTestKey failed: %v", err)
	}

	err = im.AddIdentity(key1, 0, false, false, "db-uuid-1", "entry-uuid-1")
	if err != nil {
		t.Fatalf("AddIdentity failed: %v", err)
	}

	if im.Count() != 1 {
		t.Errorf("expected 1 key after add, got %d", im.Count())
	}

	// List should return the key.
	listed := im.ListIdentities()
	if len(listed) != 1 {
		t.Fatalf("expected 1 key in list, got %d", len(listed))
	}
	if listed[0].Key.Fingerprint() != key1.Fingerprint() {
		t.Error("listed key fingerprint does not match")
	}

	// FindByFingerprint should find the key.
	fp := key1.Fingerprint()
	found := im.FindIdentityByFingerprint(fp)
	if found == nil {
		t.Fatal("FindIdentityByFingerprint returned nil for existing key")
	}
	if found.DBUUID != "db-uuid-1" {
		t.Errorf("DBUUID = %q, want db-uuid-1", found.DBUUID)
	}
	if found.EntryUUID != "entry-uuid-1" {
		t.Errorf("EntryUUID = %q, want entry-uuid-1", found.EntryUUID)
	}

	// Remove the key.
	err = im.RemoveIdentity(fp)
	if err != nil {
		t.Fatalf("RemoveIdentity failed: %v", err)
	}

	if im.Count() != 0 {
		t.Errorf("expected 0 keys after remove, got %d", im.Count())
	}

	// FindByFingerprint should return nil after removal.
	found = im.FindIdentityByFingerprint(fp)
	if found != nil {
		t.Error("FindIdentityByFingerprint should return nil after removal")
	}
}

